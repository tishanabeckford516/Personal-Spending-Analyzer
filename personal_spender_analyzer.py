import pandas as pd

data = {
    "Date": [
        "2026-01-03", "2026-01-05", "2026-01-08",
        "2026-01-12", "2026-01-15", "2026-01-18",
        "2026-02-02", "2026-02-06", "2026-02-10",
        "2026-02-14", "2026-02-20", "2026-02-25"
    ],
    "Category": [
        "Food", "Transportation", "Bills",
        "Shopping", "Food", "Entertainment",
        "Food", "Transportation", "Bills",
        "Shopping", "Food", "Entertainment"
    ],
    "Description": [
        "Groceries", "Gas", "Phone bill",
        "Clothes", "Lunch", "Movie",
        "Groceries", "Gas", "Utilities",
        "Shoes", "Dinner", "Concert"
    ],
    "Amount": [
        65.50, 35.00, 60.00,
        45.00, 18.50, 15.00,
        72.00, 40.00, 85.00,
        55.00, 24.00, 30.00
    ]
}

df = pd.DataFrame(data)

print("Personal Spending Analyzer")
display(df)

print("Dataset size:")
print(df.shape)

print("\nFirst 5 transactions:")
display(df.head())

print("\nData information:")
df.info()

print("\nMissing values:")
print(df.isnull().sum())

# Convert the Date column into a date format
df["Date"] = pd.to_datetime(df["Date"])

# Check the data types
print("Updated data types:")
print(df.dtypes)

# Check for duplicate transactions
print("\nNumber of duplicate rows:")
print(df.duplicated().sum())

# Calculate total spending in each category
category_spending = df.groupby("Category")["Amount"].sum()

# Sort from highest spending to lowest
category_spending = category_spending.sort_values(ascending=False)

print("Total Spending by Category:")
display(category_spending)

import matplotlib.pyplot as plt

# Create a bar chart
category_spending.plot(kind="bar")

# Add a title and labels
plt.title("Total Spending by Category")
plt.xlabel("Category")
plt.ylabel("Amount Spent ($)")

# Make the labels easier to read
plt.xticks(rotation=45)

# Display the chart
plt.tight_layout()
plt.show()

# Extract the month from each transaction date
df["Month"] = df["Date"].dt.strftime("%B")

# Calculate total spending for each month
monthly_spending = df.groupby("Month")["Amount"].sum()

print("Total Spending by Month:")
display(monthly_spending)

# Create a chart of monthly spending
monthly_spending.plot(kind="bar")

# Add a title and labels
plt.title("Monthly Spending Comparison")
plt.xlabel("Month")
plt.ylabel("Total Spent ($)")

# Display the chart
plt.tight_layout()
plt.show()

# Calculate summary statistics
total_spending = df["Amount"].sum()
average_spending = df["Amount"].mean()
largest_transaction = df["Amount"].max()

print(f"Total spending: ${total_spending:.2f}")
print(f"Average transaction: ${average_spending:.2f}")
print(f"Largest transaction: ${largest_transaction:.2f}")

# Sort transactions from highest amount to lowest
top_expenses = df.sort_values(
    by="Amount",
    ascending=False
)

# Display the 5 most expensive transactions
print("Top 5 Expenses:")
display(top_expenses[["Date", "Category", "Description", "Amount"]].head(5))